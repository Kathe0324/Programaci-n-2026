#Inputs
num1 = int(input("Enter a number: "))
num2 = int(input("Enter a second number: "))

#Processes
sum = num1 + num2 #subtraction, multiply, divide
subtraction = num1 - num2
multiplication = num1 * num2
division = num1 / num2

#Outputs #subtraction, multiply, divide
print(f"The result of the addition  {num1} + {num2} is: ",sum)
print(f"The result of the subtraction  {num1} - {num2} is: ",subtraction)
print(f"The result of the multiplication  {num1} * {num2} is: ",multiplication)
print(f"The result of the division  {num1} / {num2} is: ",division)
