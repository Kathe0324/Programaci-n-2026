#Entrada
voltaje = float(input("Ingrese el valor del Voltaje: "))
corriente = float(input("Ingrese el valor de la corriente: "))

#Proceso
resistencia = voltaje / corriente

#Salida
print("La resistencia seria de: ",resistencia) 